"""Автоматическое создание саммари когда контекст чата
приближается к лимиту токенов.

Саммари генерируется через ChatGPT (тот же браузер) и сохраняется
как markdown-файл для инъекции в начало нового чата.
"""

import os
import time
from loguru import logger
from config import SUMMARY_DIR

SUMMARY_PROMPT = """Создай ПОДРОБНОЕ резюме (summary) всего нашего диалога для переноса контекста в новый чат.

Резюме ДОЛЖНО содержать все следующие разделы:

## 1. Проект
- Название, путь на диске, язык/фреймворк
- Ключевые файлы и структура проекта

## 2. Задача
- Что пользователь хочет сделать (текущая задача)
- Общая цель проекта (если обсуждалась)

## 3. Что уже сделано
- Какие файлы созданы или изменены (с путями)
- Ключевые технические решения и почему они приняты
- Код/конфиги, которые критичны для понимания

## 4. Текущее состояние
- На чём остановились
- Что работает, что НЕ работает
- Последние ошибки/логи если были

## 5. Важные детали
- Пути к файлам, конфигам, БД
- Версии библиотек, runtime
- Workaround-ы, известные ограничения
- Переменные окружения, порты, credentials

## 6. Следующие шаги
- Что конкретно нужно делать дальше
- Приоритеты задач

Формат: markdown. Будь МАКСИМАЛЬНО подробен — это единственный контекст, который получит модель в новом чате.
Включай конкретные пути, имена файлов, фрагменты кода где это критично.
Длина: 2000-5000 слов."""


def ensure_summary_dir():
    """Создаёт директорию для саммари если не существует."""
    os.makedirs(SUMMARY_DIR, exist_ok=True)


def build_summary_prompt() -> str:
    """Возвращает промпт для генерации саммари."""
    return SUMMARY_PROMPT


def save_summary(summary_text: str, client_id: str) -> str:
    """Сохраняет саммари в файл, возвращает путь."""
    ensure_summary_dir()
    ts = int(time.time())
    filename = f"summary_{client_id}_{ts}.md"
    path = os.path.join(SUMMARY_DIR, filename)
    with open(path, "w", encoding="utf-8") as f:
        f.write(summary_text)
    logger.info("📋 Саммари сохранено: {} ({} символов)", path, len(summary_text))
    return path


def build_context_injection(summary_text: str) -> str:
    """Формирует текст для инъекции в начало нового чата.

    Оборачивает саммари в чёткие маркеры, чтобы модель понимала
    что это контекст из прошлого чата, а не новая задача.
    """
    return f"""[КОНТЕКСТ ИЗ ПРЕДЫДУЩЕГО ЧАТА — ПРОЧИТАЙ ВНИМАТЕЛЬНО]

Ниже — подробное резюме предыдущей рабочей сессии.
Ты продолжаешь эту работу. Весь контекст ниже актуален.

---

{summary_text}

---

[КОНЕЦ КОНТЕКСТА. ПРОДОЛЖАЙ РАБОТУ С ТОГО МЕСТА, ГДЕ ОСТАНОВИЛИСЬ.]

"""


def get_latest_summary(client_id: str) -> str | None:
    """Возвращает текст последнего саммари для данного клиента, или None."""
    ensure_summary_dir()
    prefix = f"summary_{client_id}_"
    files = [
        f for f in os.listdir(SUMMARY_DIR)
        if f.startswith(prefix) and f.endswith(".md")
    ]
    if not files:
        return None
    latest = sorted(files)[-1]
    path = os.path.join(SUMMARY_DIR, latest)
    with open(path, "r", encoding="utf-8") as f:
        return f.read()
